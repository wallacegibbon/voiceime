package ibus

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/wallacegibbon/voiceime/internal/config"
)

// Component is the XML description of the engine.
//
// The daemon reads these files to build its registry: it learns the bus name the
// engine process will own (<name>), what it is called in a menu (<longname>) and,
// critically, the command it should spawn when the engine is activated (<exec>).
type Component struct {
	// Name is the component name and the D-Bus well-known name of the engine
	// process. IBus uses one value for both.
	Name        string
	Description string
	Exec        string
	Version     string
	Author      string
	License     string
	Homepage    string
	TextDomain  string

	// EngineName is what `ibus engine <name>` and the config use.
	EngineName string
	Language   string
	LongName   string
	EngineDesc string
	Symbol     string
	Rank       int
	Icon       string
}

// DefaultComponent returns the component description for this build.
func DefaultComponent(cfg *config.Config, execPath string) Component {
	return Component{
		Name:        DefaultComponentName,
		Description: "Voiceime speech input method",
		Exec:        execPath,
		Version:     "0.1.0",
		Author:      "voiceime",
		License:     "GPL",
		Homepage:    "https://github.com/wallacegibbon/voiceime",
		TextDomain:  "voiceime",
		EngineName:  cfg.IBusEngineName,
		Language:    cfg.Language,
		LongName:    "Voiceime (speech)",
		EngineDesc:  "Dictate into any application with a local speech recogniser",
		Symbol:      "&#x1F3A4;", // microphone
		Rank:        1,
	}
}

// XML renders the component in the format ibus-daemon parses.
//
// The element names and nesting were taken from a working component
// (/usr/share/ibus/component/pinyin.xml) rather than from documentation, and the
// output was verified by loading it into a sandbox daemon and seeing the engine
// appear in `ibus list-engine`.
func (c Component) XML() string {
	var builder strings.Builder
	builder.WriteString("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n")
	builder.WriteString("<!-- Generated by `voiceime engine install`; regenerated on each install. -->\n")
	builder.WriteString("<component>\n")
	writeElement(&builder, 1, "name", c.Name)
	writeElement(&builder, 1, "description", c.Description)
	writeElement(&builder, 1, "exec", c.Exec)
	writeElement(&builder, 1, "version", c.Version)
	writeElement(&builder, 1, "author", c.Author)
	writeElement(&builder, 1, "license", c.License)
	writeElement(&builder, 1, "homepage", c.Homepage)
	writeElement(&builder, 1, "textdomain", c.TextDomain)
	builder.WriteString("\t<engines>\n")
	builder.WriteString("\t\t<engine>\n")
	writeElement(&builder, 3, "name", c.EngineName)
	writeElement(&builder, 3, "language", c.Language)
	writeElement(&builder, 3, "license", c.License)
	writeElement(&builder, 3, "author", c.Author)
	writeElement(&builder, 3, "layout", "default")
	writeElement(&builder, 3, "longname", c.LongName)
	writeElement(&builder, 3, "description", c.EngineDesc)
	writeElement(&builder, 3, "rank", fmt.Sprint(c.Rank))
	if c.Symbol != "" {
		writeElement(&builder, 3, "symbol", c.Symbol)
	}
	if c.Icon != "" {
		writeElement(&builder, 3, "icon", c.Icon)
	}
	builder.WriteString("\t\t</engine>\n")
	builder.WriteString("\t</engines>\n")
	builder.WriteString("</component>\n")
	return builder.String()
}

func writeElement(builder *strings.Builder, depth int, name, value string) {
	indent := strings.Repeat("\t", depth)
	// The engine will not start if the runner is given a bare command, so an
	// empty value is omitted rather than written as an empty element.
	if strings.TrimSpace(value) == "" {
		return
	}
	fmt.Fprintf(builder, "%s<%s>%s</%s>\n", indent, name, escapeXML(value), name)
}

func escapeXML(value string) string {
	replacer := strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;")
	return replacer.Replace(value)
}

// ComponentDir is where voiceime keeps its own component file. IBus does not scan
// this directory by default; see InstallPaths.
func ComponentDir() string { return filepath.Join(config.DataDir(), "component") }

// ComponentPath is the file `voiceime engine install` writes.
func ComponentPath() string { return filepath.Join(ComponentDir(), "voiceime.xml") }

// InstallPaths is the value IBUS_COMPONENT_PATH must have for the daemon to find
// our component *and* keep the system engines.
//
// This is not cosmetic: setting IBUS_COMPONENT_PATH replaces the default search
// path rather than adding to it, so a value naming only our directory would hide
// every system engine. Verified in a sandbox daemon: 1270 engines without the
// variable, 2 with it set to one directory, 1271 with both directories listed.
func InstallPaths(systemDir string) string {
	if systemDir == "" {
		systemDir = "/usr/share/ibus/component"
	}
	return ComponentDir() + ":" + systemDir
}

// Install writes the component file and returns the file path.
func Install(component Component) (string, error) {
	if err := os.MkdirAll(ComponentDir(), 0o755); err != nil {
		return "", err
	}
	path := ComponentPath()
	if err := os.WriteFile(path, []byte(component.XML()), 0o644); err != nil {
		return "", err
	}
	return path, nil
}

// Uninstall removes the component file.
func Uninstall() error {
	err := os.Remove(ComponentPath())
	if os.IsNotExist(err) {
		return nil
	}
	return err
}

// Installed reports whether the component file is present.
func Installed() bool {
	info, err := os.Stat(ComponentPath())
	return err == nil && !info.IsDir()
}
