func buildExceptions(phrases []string) map[rune][][]rune {
	grouped := map[rune][][]rune{}
	for _, phrase := range phrases {
		runes := []rune(phrase)
		if len(runes) == 0 {
			continue
		}
		grouped[runes[0]] = append(grouped[runes[0]], runes)
	}
	for first := range grouped {
		sort.Slice(grouped[first], func(i, j int) bool {
			return len(grouped[first][i]) > len(grouped[first][j])
		})
	}
	return grouped
}
